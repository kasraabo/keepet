#!/usr/bin/env python3
"""Local-only old-image -> real updater -> rollback rehearsal on disposable Compose volumes."""
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import time
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
os.umask(0o077)
folder = Path(tempfile.mkdtemp(prefix='keepet-rollback-rehearsal-'))
repo = folder / 'repo'
project = 'keepet_rollback_rehearsal_' + str(os.getpid())
env = os.environ.copy()
env.update(COMPOSE_PROJECT_NAME=project, KEEPET_HEALTH_URL='http://127.0.0.1:18180/health',
           BUILDX_CONFIG='/workspace/.cache/buildx')
log = (folder / 'rehearsal.log').open('w')


def run(args, cwd=repo, **kw):
    return subprocess.run(args, cwd=cwd, env=env, check=True, stdout=log, stderr=log, **kw)


def output(args, cwd=repo):
    return subprocess.check_output(args, cwd=cwd, env=env, stderr=log, text=True).strip()


def compose(*args):
    return ['docker', 'compose', *args]


def sql(query, conf=None):
    cmd = compose('exec', '-T', 'db', 'psql', '-X', '-U', 'keepet', '-d', 'keepet', '-Atq', '-v', 'ON_ERROR_STOP=1', '-c', query)
    if conf:
        cmd = ['docker', 'compose', '-p', conf[0], '-f', str(conf[1]), *cmd[2:]]
    return output(cmd)


def health():
    for _ in range(80):
        try:
            with urllib.request.urlopen(env['KEEPET_HEALTH_URL'], timeout=1) as r:
                if r.status == 200 and r.read() == b'ok':
                    return
        except OSError:
            pass
        time.sleep(0.5)
    raise RuntimeError('local application health failed')


active_recovery = None
try:
    run(['git', 'clone', '--shared', '--no-hardlinks', str(ROOT), str(repo)], cwd=folder)
    # Build a local-only release branch containing the candidate scripts. Never push this fixture.
    for p in ROOT.joinpath('scripts').iterdir():
        if p.is_file():
            shutil.copyfile(p, repo / 'scripts' / p.name)
    candidate = json.loads(output(['docker', 'compose', 'config', '--format', 'json']))
    candidate['services']['app']['ports'] = [{'target': 8080, 'published': '18180', 'host_ip': '127.0.0.1', 'protocol': 'tcp'}]
    candidate['services']['app']['image'] = 'keepet-release-rehearsal:latest'
    candidate['services']['app']['build'] = {'context': str(repo)}
    candidate['services']['db']['image'] = output(['docker', 'inspect', 'keepet-db', '--format', '{{.Image}}'])
    # Remove absolute project volume/network names generated by Compose normalization.
    candidate['volumes'] = {'db-data': {}, 'app-secrets': {}}
    candidate.pop('name', None)
    candidate.pop('networks', None)
    for svc in candidate['services'].values():
        svc.pop('networks', None)
    (repo / 'compose.yaml').write_text(json.dumps(candidate, indent=2))
    run(['git', 'add', 'scripts', 'compose.yaml'])
    run(['git', '-c', 'user.name=Release rehearsal', '-c', 'user.email=release@example.test', 'commit', '-m', 'Local candidate fixture'])
    target = output(['git', 'rev-parse', 'HEAD'])
    run(['git', 'clone', '--bare', str(repo), str(folder / 'origin.git')], cwd=folder)
    run(['git', '--git-dir=' + str(folder / 'origin.git'), 'update-ref', 'refs/heads/main', target])
    run(['git', 'remote', 'set-url', 'origin', str(folder / 'origin.git')])
    run(['git', 'checkout', '--detach', '86a4baa2618c2e3f0af025b2347b13f0b911d3c7'])
    old = json.loads(json.dumps(candidate))
    old['services']['app'].pop('build', None)
    old['services']['app']['image'] = os.getenv('KEEPET_LEGACY_TEST_IMAGE', 'keepet_update_smoke-app:latest')
    (repo / 'compose.yaml').write_text(json.dumps(old, indent=2))
    run(compose('up', '-d', '--no-build', '--pull', 'never'))
    health()
    assert sql("SELECT version FROM schema_migrations") == '11'
    sql("INSERT INTO users(id,phone,name,role) VALUES('rollback-owner','09123336660','کاربر بکاپ','owner')")
    sql("SELECT wallet_post('rollback-owner','admin_cash',700000,0,0,'rehearsal-funds',NULL,NULL,'old balance')")
    sql("INSERT INTO tickets(id,user_id,subject,body,email) VALUES('old-rehearsal-ticket','rollback-owner','old ticket','private historical content','local@example.test')")
    # Exercise private-key backup without real credentials. Cipher decryption is tested by the Go upgrade test.
    key = folder / 'settings.key'
    key.write_bytes(os.urandom(32))
    app = output(compose('ps', '-q', 'app'))
    run(['docker', 'cp', str(key), app + ':/var/lib/keepet/settings.key'])
    run(['docker', 'exec', '-u', '0', app, 'sh', '-c', 'chown keepet:keepet /var/lib/keepet/settings.key; chmod 600 /var/lib/keepet/settings.key'])
    run(['bash', str(ROOT / 'scripts/update-arvan-trial.sh'), str(repo), target])
    health()
    assert sql("SELECT version::text||':'||dirty::text FROM schema_migrations") == '21:false'
    backup = next((folder / 'keepet-backups').iterdir())
    sql("SELECT wallet_post('rollback-owner','admin_cash',12345,0,0,'new-after-upgrade',NULL,NULL,'new balance')")
    sql("INSERT INTO tickets(id,user_id,subject,body,email) VALUES('new-rehearsal-ticket','rollback-owner','new ticket','new content preserved','local@example.test')")
    rollback = backup / 'rollback-arvan-trial.sh'
    run(['bash', str(rollback), str(repo), str(backup), '--check'])
    # Corruption must be detected while the current app remains running.
    with (backup / 'database.dump').open('ab') as f:
        f.write(b'corruption-probe')
    result = subprocess.run(['bash', str(rollback), str(repo), str(backup), '--check'], cwd=repo, env=env, stdout=log, stderr=log)
    assert result.returncode != 0
    health()
    with (backup / 'database.dump').open('r+b') as f:
        f.truncate(f.seek(0, 2) - len(b'corruption-probe'))
    # Inject an old-app startup failure after a valid isolated DB restore/cutover.
    # The healthy current app must be resumed on its untouched current DB.
    faulty = folder / 'faulty-backup'
    shutil.copytree(backup, faulty)
    bad_config = json.loads((faulty / 'compose.resolved.json').read_text())
    bad_config['services']['app']['environment']['APP_MODE'] = 'production'
    (faulty / 'compose.resolved.json').write_text(json.dumps(bad_config))
    inventory = []
    for f in sorted(faulty.rglob('*')):
        if f.is_file() and f.name != 'SHA256SUMS':
            inventory.append(hashlib.sha256(f.read_bytes()).hexdigest() + '  ./' + str(f.relative_to(faulty)))
    (faulty / 'SHA256SUMS').write_text('\n'.join(inventory) + '\n')
    failed = subprocess.run(['bash', str(faulty / 'rollback-arvan-trial.sh'), str(repo), str(faulty), '--restore'], cwd=repo, env=env, stdout=log, stderr=log)
    assert failed.returncode != 0
    fault_dirs = list((folder / 'keepet-recoveries').glob('*'))
    assert len(fault_dirs) == 1 and (fault_dirs[0] / 'before-rollback.dump').stat().st_size > 0, 'failure must happen after cutover'
    assert not (repo / '.keepet-recovery').exists()
    health()
    assert sql("SELECT version::text||':'||dirty::text FROM schema_migrations") == '21:false'
    assert sql("SELECT cash FROM wallets WHERE user_id='rollback-owner'") == '712345'
    run(['bash', str(rollback), str(repo), str(backup), '--restore'])
    recovery = Path((repo / '.keepet-recovery').read_text().strip())
    recovery_project = (recovery / 'project.txt').read_text().strip()
    active_recovery = (recovery_project, recovery / 'compose.json')
    health()
    assert sql("SELECT version::text||':'||dirty::text FROM schema_migrations", active_recovery) == '11:false'
    assert sql("SELECT cash FROM wallets WHERE user_id='rollback-owner'", active_recovery) == '700000'
    assert sql("SELECT body FROM tickets WHERE id='old-rehearsal-ticket'", active_recovery) == 'private historical content'
    assert sql("SELECT count(*) FROM tickets WHERE id='new-rehearsal-ticket'", active_recovery) == '0'
    # The inactive original database retains every newer record.
    assert sql("SELECT cash FROM wallets WHERE user_id='rollback-owner'") == '712345'
    assert sql("SELECT count(*) FROM tickets WHERE id='new-rehearsal-ticket'") == '1'
    restored_app = output(['docker', 'compose', '-p', recovery_project, '-f', str(recovery / 'compose.json'), 'ps', '-q', 'app'])
    restored_key = folder / 'restored.key'
    run(['docker', 'cp', restored_app + ':/var/lib/keepet/settings.key', str(restored_key)])
    assert restored_key.read_bytes() == key.read_bytes()
    assert (recovery / 'before-rollback.dump').stat().st_size > 0
    # Normal updater must refuse the inactive checkout after a recovery cutover.
    blocked = subprocess.run(['bash', str(ROOT / 'scripts/update-arvan-trial.sh'), str(repo), target], cwd=repo, env=env, stdout=log, stderr=log)
    assert blocked.returncode != 0
    (folder / 'result.json').write_text(json.dumps({'result':'PASS','upgrade':'11 -> 21','rollback':'21 -> isolated 11','newer_records':'preserved in original database and safety dump','private_key':'matching','corrupt_backup':'rejected before cutover','failed_rollback':'current app safely resumed on untouched database'},indent=2)+'\n')
    print('PASS: actual Docker upgrade, checked backup, corrupt-backup rejection, previous-image/database/key rollback, preserved newer data and guarded inactive checkout.')
finally:
    for recovery_dir in (folder / 'keepet-recoveries').glob('*'):
        if (recovery_dir / 'project.txt').exists():
            name = (recovery_dir / 'project.txt').read_text().strip()
            if re.fullmatch(r'keepet_recovery_[0-9_]+', name):
                subprocess.run(['docker', 'compose', '-p', name, '-f', str(recovery_dir / 'compose.json'), 'down', '-v'], env=env, stdout=log, stderr=log)
    if (repo / 'compose.yaml').exists():
        subprocess.run(compose('down', '-v'), cwd=repo, env=env, stdout=log, stderr=log)
    log.close()
    print('Evidence:', folder)
